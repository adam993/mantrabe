#!/usr/bin/env node
// Stage the latest Android APK into public/ so the web build (dist/) can
// serve it as a download. Also generates src/build-info.js so the UI knows
// whether the download button should be visible.
//
// Run on every `yarn build`. The native Android build script removes
// dist/mantrabe-android.apk after `cap sync` so the APK isn't recursively
// bundled inside itself.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC  = path.join(ROOT, 'release', 'mantrabe-android-latest.apk');
const DST  = path.join(ROOT, 'public', 'mantrabe-android.apk');
const INFO = path.join(ROOT, 'src', 'build-info.ts');

let hasApk = false;
let bytes = 0;

if (fs.existsSync(SRC)) {
  fs.mkdirSync(path.dirname(DST), { recursive: true });
  fs.copyFileSync(SRC, DST);
  hasApk = true;
  bytes = fs.statSync(SRC).size;
  console.log(
    `prepare-public-apk: copied ${(bytes / 1024 / 1024).toFixed(1)} MB -> public/mantrabe-android.apk`,
  );
} else {
  // Remove a stale copy so we don't ship an outdated APK with the web bundle.
  if (fs.existsSync(DST)) fs.unlinkSync(DST);
  console.log(
    'prepare-public-apk: no release/mantrabe-android-latest.apk yet — download button will be hidden',
  );
}

fs.mkdirSync(path.dirname(INFO), { recursive: true });
const out = `// Generated by scripts/prepare-public-apk.cjs — do not edit by hand.
export const HAS_ANDROID_APK = ${hasApk};
export const ANDROID_APK_BYTES = ${bytes};
`;
fs.writeFileSync(INFO, out);
